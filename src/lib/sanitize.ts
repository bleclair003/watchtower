/**
 * Source content is untrusted. React escapes text by default; this module
 * covers the remaining injection vector — URLs placed in href attributes.
 */
export function safeExternalUrl(raw: string | null | undefined): string | null {
  if (!raw) return null;
  try {
    const u = new URL(raw);
    return u.protocol === 'https:' || u.protocol === 'http:' ? u.toString() : null;
  } catch {
    return null;
  }
}
